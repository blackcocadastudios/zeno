NUM = r"-?\d*\.?\d+(?:e-?\d+)?"


def f(v):
    v = float(v)
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def circle(cx, cy, r):
    cx, cy, r = float(cx), float(cy), float(r)
    return (f"M{f(cx - r)} {f(cy)}a{f(r)} {f(r)} 0 1 0 {f(2 * r)} 0"
            f"a{f(r)} {f(r)} 0 1 0 {f(-2 * r)} 0Z")


def ellipse(cx, cy, rx, ry):
    cx, cy, rx, ry = map(float, (cx, cy, rx, ry))
    return (f"M{f(cx - rx)} {f(cy)}a{f(rx)} {f(ry)} 0 1 0 {f(2 * rx)} 0"
            f"a{f(rx)} {f(ry)} 0 1 0 {f(-2 * rx)} 0Z")


def rect(x, y, w, h, rx=None, ry=None):
    x, y, w, h = map(float, (x, y, w, h))
    if rx is None and ry is None:
        return f"M{f(x)} {f(y)}h{f(w)}v{f(h)}h{f(-w)}Z"
    rx = float(rx if rx is not None else ry)
    ry = float(ry if ry is not None else rx)
    rx, ry = min(rx, w / 2), min(ry, h / 2)
    return (f"M{f(x + rx)} {f(y)}h{f(w - 2 * rx)}a{f(rx)} {f(ry)} 0 0 1 {f(rx)} {f(ry)}"
            f"v{f(h - 2 * ry)}a{f(rx)} {f(ry)} 0 0 1 {f(-rx)} {f(ry)}"
            f"h{f(-(w - 2 * rx))}a{f(rx)} {f(ry)} 0 0 1 {f(-rx)} {f(-ry)}"
            f"v{f(-(h - 2 * ry))}a{f(rx)} {f(ry)} 0 0 1 {f(rx)} {f(-ry)}Z")


def points(pts, close):
    nums = re.findall(NUM, pts)
    pairs = list(zip(nums[0::2], nums[1::2]))
    d = f"M{f(pairs[0][0])} {f(pairs[0][1])}" + "".join(f"L{f(a)} {f(b)}" for a, b in pairs[1:])
    return d + ("Z" if close else "")


def convert(svg_path):
    root = ET.parse(svg_path).getroot()
    out = []
    for el in root.iter():
        tag = el.tag.split("}")[-1]
        a = el.attrib
        if tag == "path":
            out.append(a["d"])
        elif tag == "circle":
            out.append(circle(a["cx"], a["cy"], a["r"]))
        elif tag == "ellipse":
            out.append(ellipse(a["cx"], a["cy"], a["rx"], a["ry"]))
        elif tag == "rect":
            out.append(rect(a.get("x", 0), a.get("y", 0), a["width"], a["height"], a.get("rx"), a.get("ry")))
        elif tag == "line":
            out.append(f"M{f(a['x1'])} {f(a['y1'])}L{f(a['x2'])} {f(a['y2'])}")
        elif tag == "polyline":
            out.append(points(a["points"], False))
        elif tag == "polygon":
            out.append(points(a["points"], True))
    return out


def main():
    src, dest = sys.argv[1], sys.argv[2]
    lines = [
        "// Generated by tools/design/lucide_to_compose.py from Lucide (ISC License,",
        "// https://lucide.dev). Do not edit by hand; regenerate instead.",
        "package com.blackcocadastudios.zeno.design.icon",
        "",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "",
        "/** Zeno's line icons: Lucide geometry drawn with a 1.5 ink stroke. */",
        "object ZenoIcons {",
    ]
    for name, file in ICONS.items():
        paths = convert(os.path.join(src, file + ".svg"))
        joined = ",\n            ".join('"' + p + '"' for p in paths)
        lines.append(f"    val {name}: ImageVector by lazy {{")
        lines.append(f"        lineIcon(\n            \"{name}\",\n            {joined},\n        )")
        lines.append("    }")
        lines.append("")
    lines.append("    /** Every icon with its name, for galleries and tests. */")
    lines.append("    val all: List<Pair<String, ImageVector>>")
    lines.append("        get() = listOf(")
    for name in ICONS:
        lines.append(f'            "{name}" to {name},')
    lines.append("        )")
    lines.append("}")
    with open(dest, "w") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
